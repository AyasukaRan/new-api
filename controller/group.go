package controller

import (
	"net/http"

	"github.com/QuantumNous/new-api/service"
	"github.com/QuantumNous/new-api/setting"
	"github.com/QuantumNous/new-api/setting/ratio_setting"

	"github.com/gin-gonic/gin"
)

func GetGroups(c *gin.Context) {
	groupNames := make([]string, 0)
	for groupName := range ratio_setting.GetGroupRatioCopy() {
		groupNames = append(groupNames, groupName)
	}
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
		"data":    groupNames,
	})
}

func GetUserGroups(c *gin.Context) {
	usableGroups := make(map[string]map[string]any)
	userGroup := c.GetString("user_group")
	for group, description := range service.GetUserVisibleGroups(userGroup) {
		if group == "auto" {
			usableGroups[group] = map[string]any{"ratio": "auto", "desc": setting.GetUsableGroupDescription("auto")}
			continue
		}
		usableGroups[group] = map[string]any{"ratio": service.GetUserGroupRatio(userGroup, group), "desc": description}
	}
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
		"data":    usableGroups,
	})
}
